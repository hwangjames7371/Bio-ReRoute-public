def _skip(line: str) -> bool:
    return any(p.search(line) for p in SKIP_LINE)


def _fenced(text: str) -> set:
    """```…``` 안의 줄 번호 집합.

    **코드 펜스는 건너뛴다.** 그 안에는 명령 예시와 *과거 상태를 인용한
    증거*가 들어간다 — 결함 59 항목 자체가 옛 드리프트를 펜스로 인용하고
    있고, 그걸 새 드리프트로 세면 이 검사기가 영원히 붉어진다.

    **한계를 적어 둔다** — 펜스 안에서 진짜 드리프트가 나면 못 잡는다.
    현재 상태를 주장하는 문장은 산문이나 표에 두는 것이 규칙이고,
    이 검사기는 그 규칙을 전제로 한다.
    """
    out, on = set(), False
    for i, line in enumerate(text.split("\n"), 1):
        if line.lstrip().startswith("```"):
            on = not on
            out.add(i)
            continue
        if on:
            out.add(i)
    return out


def _hits(text: str, pat: str) -> Dict[str, List[int]]:
    skip = _fenced(text)
    out = defaultdict(list)
    for m in re.finditer(pat, text):
        ln = text[:m.start()].count("\n") + 1
        if ln in skip:
            continue
        out[m.group(1)].append(ln)
    return out


# ── `a/b = p%` 의 산수가 맞는가 (결함 93) ─────────────────────────
#
#   08-10 사고: 결함 수를 89→92 로 일괄 치환하다가 슬라이드의
#   `유형 충돌 89/457 = 19.5%` 가 **`92/457 = 19.5%`** 가 됐다.
#   92/457 은 20.1% 다. **분자와 백분율이 서로 안 맞는 숫자**가
#   발표자료에 박혔고, 문서 간 비교로는 안 잡힌다 — 그 값은 슬라이드
#   한 곳에만 있어서 *"문서 N곳 일치"* 로 통과한다.
#
#   일괄 치환 사고는 이번이 **다섯 번째**다. 넷을 겪는 동안
#   *"조심하자"* 만 했고 검사하는 코드를 안 만들었다. 이게 그 코드다.
#
#   **문서끼리 대조하지 않는다. 한 문장 안에서 자기 모순을 찾는다** —
#   그래서 값이 한 곳에만 있어도 잡힌다.
_RATIO = re.compile(r"(\d[\d,]*)\s*/\s*(\d[\d,]*)\s*=\s*(\d+(?:\.\d+)?)\s*%")


def ratio_errors(root: str = ROOT) -> List[Dict[str, Any]]:
    """`a/b = p%` 꼴을 전부 찾아 **직접 나눠 본다.**

    허용 오차는 반올림 자릿수에서 나온다 — `19.5%` 는 소수 1자리이므로
    ±0.05%p 를 준다. 정수 표기(`20%`)면 ±0.5%p 다. **넉넉히 주는 쪽이
    맞다** — 이 검사기의 일은 오탐으로 사람을 지치게 하는 게 아니라
    *치환 사고처럼 크게 어긋난 것*을 잡는 것이다.
    """
    out = []
    for fn in sorted(set(DOCS)) + ["slides/build_deck.py"]:
        p = os.path.join(root, fn)
        if not os.path.exists(p):
            continue
        try:
            txt = open(p, encoding="utf-8").read()
        except Exception:
            continue
        skip = _fenced(txt) if fn.endswith(".md") else set()
        for m in _RATIO.finditer(txt):
            ln = txt[:m.start()].count("\n") + 1
            if ln in skip:
                continue
            a = int(m.group(1).replace(",", ""))
            b = int(m.group(2).replace(",", ""))
            said = float(m.group(3))
            if b == 0:
                continue
            real = 100.0 * a / b
            dec = len(m.group(3).split(".")[1]) if "." in m.group(3) else 0
            tol = 0.5 * (10 ** -dec)
            if abs(real - said) > tol:
                out.append({"파일": fn, "줄": ln, "적힌 것": m.group(0),
                            "실제": round(real, 2)})
    return out


