def _spec_count(root: str = ROOT) -> int:
    """**사전명세가 몇 개인가** — 파일을 세서 낸다. 사람이 안 센다.

    ⚠ `사전명세*.md` 를 그냥 세면 **틀린다.** 그중 둘은 사전 등록이
      아니라 **반증 기록**이다 —

        사전명세_라우터그래프_반증.md   *«봉인은 안 지운다»*
        사전명세_조건부판정_반증.md     *«원본은 그대로 두고 이 문서가 위에 붙는다»*

      둘 다 **이미 봉인된 명세의 전제가 깨졌다는 기록**이고, 그래서
      자기 봉인이 없다. 새 사전 등록으로 세면 **우리가 우리 수를 부풀린다.**
      `_봉인.json` 이 있는 것만 센다 — **봉인이 없는 사전명세는
      사전명세가 아니다.** 그게 이 프로젝트가 파는 것이다.
    """
    import glob as _g
    sealed = {os.path.basename(x) for x in sealed_docs(root)}
    return sum(1 for p in _g.glob(os.path.join(root, "사전명세*.md"))
               if os.path.basename(p) in sealed)


def audit(root: str = ROOT, truth_tests: Optional[int] = None) -> Dict[str, Any]:
    res = {"항목": [], "불일치": 0, "확인한_문서": 0}
    texts = {}
    for d in DOCS:
        p = os.path.join(root, d)
        if os.path.exists(p):
            texts[d] = open(p, encoding="utf-8").read()
    for d, reader in EXTRA:
        p = os.path.join(root, d)
        if not os.path.exists(p):
            continue
        texts[d] = reader(p) if reader else open(p, encoding="utf-8").read()
    res["확인한_문서"] = len(texts)

    # ── 문서끼리 같은 것만으로는 부족하다 ──────────────────
#
    #   실측: 문서 4곳이 모두 `664건` 으로 **일치**했는데 실제는 691 이었다.
    #   **전부 같이 틀리면 이 감사는 통과한다.** 그래서 정본과도 대조한다.
#
    #   다만 여기서 시험을 직접 돌리지 않는다 — `preflight` 이 이미 돌리고,
    #   두 번 돌리면 느려서 아무도 안 쓴다. **정본은 넘겨받는다.**
    #   단독 실행일 때는 확인 못 했다고 적는다.
    res["실제_회귀시험"] = truth_tests
    res["실제_사전명세"] = _spec_count(root)
    # ── 09-24 · **결함 수도 정본(대장의 행 수)과 맞춘다** ────────────────
    #   문서 36곳이 «323» 으로 **일치**하는 동안 대장은 331 행이었다. 이 감사는
    #   문서끼리만 봐서 «일치» 였고, `countsync` 줄은 `--defects 323
    #   --old-defects 323` (아무것도 안 바꾸는 줄)을 찍었다. 그래서 매번
    #   **사람이 수를 고쳐 넣었다**(09-22 «--defects 324/325»). 결함 307 의 자리다.
    #   정본은 `evidence.defect_count()` — 시험 `test_evidence` 가 쓰는 그 함수다.
    try:
        from .. import evidence as _EV
        res["실제_결함"] = _EV.defect_count(os.path.join(root, "Bio-ReRoute_발견정리.md"))
    except Exception:
        res["실제_결함"] = None

    for name, pat, why in CHECKS:
        found = defaultdict(list)
        for d, t in texts.items():
            for v, lines in _hits(t, pat).items():
                for ln in lines:
                    if _skip(t.split("\n")[ln - 1]):
                        continue
                    found[v].append("%s:%d" % (d, ln))
        item = {"이름": name, "값": {k: v for k, v in found.items()},
                "일치": len(found) <= 1, "예외": why}
        # 회귀 시험은 **정본(실제 실행 수)** 과도 맞아야 한다.
        # 합산 표기(`34+738 = 772`)도 같은 정본을 가리켜야 한다 — 결함 68.
        if name in ("회귀 시험", "시험 합산표기") and res.get("실제_회귀시험") and found:
            real = str(res["실제_회귀시험"])
            item["정본"] = real
            if list(found) != [real]:
                item["일치"] = False
                item["정본_불일치"] = True
        # 결함 건수는 **대장의 행 수**가 정본이다 (표와 문장이 어긋나면 표가 사실)
        if name == "결함 건수" and res.get("실제_결함") and found:
            real = str(res["실제_결함"])
            item["정본"] = real
            if list(found) != [real]:
                item["일치"] = False
                item["정본_불일치"] = True
        # 사전명세 회수는 **파일을 세면 나온다** — 넘겨받을 필요가 없다
        if name == "사전명세 회수" and res.get("실제_사전명세"):
            real = str(res["실제_사전명세"])
            item["정본"] = real
            if found and list(found) != [real]:
                item["일치"] = False
                item["정본_불일치"] = True
        if not item["일치"] and not why:
            res["불일치"] += 1
        res["항목"].append(item)

    # ── 08-12 — **낡은 보정 주장이 남아 있나** (결함 132·135) ──────────
    #
    #   숫자 일치만 보면 **전부 같이 틀린 것**을 못 잡는다. 그래서 값이
    #   아니라 **주장 문구**를 본다 — 08-12에 Platt 을 적용하고 널 모형을
    #   붙였으므로 아래 문구는 더 이상 사실이 아니다.
    stale_claims = [
        ("Platt 보정은 아직 안 했다", "08-12에 적용했다"),
        ("보정에서는 기준선에 졌다", "홀드아웃에서 순서가 뒤집힌다 · 구간은 0 포함"),
        ("기준선이 더 정직하다", "같은 이유"),
    ]
    hits = []
    for d, t in texts.items():
        for ln, line in enumerate(t.split("\n"), 1):
            for claim, _why in stale_claims:
                if claim not in line:
                    continue
                # ── **인용과 주장을 가른다** ─────────────────────────
                #   결함 기록과 코드 주석은 옛 문구를 **일부러** 싣는다.
                #   그걸 «현재 주장» 으로 세면 결함 61 계열이 된다 —
                #   오늘만 이 함정에 네 번 걸렸다.
                #
                #   인용 표식: `*"…"*` · `«…»` · 결함 번호 · 주석(`#`)
                lo = line.lstrip()
                quoted = ('*"' in line or "«" in line
                          or re.search(r"결함\s*\d+", line)
                          or lo.startswith("#") or lo.startswith("//"))
                if quoted or "앞판" in line or "였다" in line:
                    continue
                hits.append("%s:%d  «%s»" % (d, ln, claim))
    res["낡은_보정주장"] = hits
    if hits:
        res["불일치"] += 1

    # ── 09-25 · **사전 기준 집계** — 정본은 `사전기준_대장.csv` 다 ────────
    #
    #   «사전 기준이 붙고 결과가 나온 넷 중 셋이 미달» 이 제출 문서 다섯과
    #   슬라이드에 박혀 있었다. 봉인 31개를 기준마다 세니 결과가 나온 기준은
    #   **39개**였다(«넷» 은 08-05 첫 봉인의 넷). 사전명세 **회수**는 위에서
    #   파일을 세어 지켰는데, **그 결과의 집계**는 아무도 안 셌다 — 결함 303
    #   이 «기계로 못 센다» 고 적은 그 자리다. 분류는 사람이 하고(대장),
    #   **문장이 대장과 같은지 · 옛 서사가 남았는지**는 여기서 본다.
    try:
        from . import prereg as _PR
        pr = _PR.check(root) + _PR.doc_problems(root)
    except Exception as e:                      # 대장이 없거나 깨졌다
        pr = ["prereg 를 못 돌렸다 — %s" % e]
    res["사전기준"] = pr
    if pr:
        res["불일치"] += 1
    return res


TRUTH_FILE = "시험정본.json"


def truth_tests(root: str = ROOT) -> Optional[dict]:
    """**시험 정본을 사람이 타이핑하지 않게 한다** (결함 307).

    08-24 저녁에 나는 `docaudit --tests 2047` 을 **손으로 쳐서** 돌리고
    «불일치 없음» 을 받았다. 그 2047 은 **문서에 적힌 값**이었다 —
    즉 **정답을 넣고 채점했다.** 같은 시각 승우 컴퓨터의 `preflight` 은
    시험을 실제로 돌려 2053 을 쥐고 «불일치 2항목» 을 냈다.

    나는 그 차이를 **환경 차이라고 세 번 적었다.** 아니었다.
    `CLAUDE.md §5` 를 인용까지 해 놓고 **인용이 방어가 아니었다.**

    그래서 정본을 파일로 남긴다. `preflight` 이 시험을 돌린 **직후에만**
    쓴다. `--tests` 없이 부르면 이 파일을 읽는다.

    ⚠ **파일도 낡는다.** 시험 코드가 이 파일보다 새로우면 «정본이 낡았다»
    고 말한다. **낡은 정본으로 초록을 내는 것이 이 결함의 내용**이므로,
    낡았으면 정본으로 쓰지 않는다.
    """
    p = os.path.join(root, TRUTH_FILE)
    if not os.path.exists(p):
        return None
    try:
        d = json.load(open(p, encoding="utf-8"))
        n = int(d.get("합"))
    except Exception:
        return None
    newest, who, seen = 0.0, None, 0
    for sub in ("tests", "bench"):
        d2 = os.path.join(root, "bioreroute", sub)
        for dirpath, _dn, files in os.walk(d2):
            if "__pycache__" in dirpath:
                continue
            for f in files:
                if not f.endswith(".py"):
                    continue
                seen += 1
                m = os.path.getmtime(os.path.join(dirpath, f))
                if m > newest:
                    newest, who = m, f
    # ⚠ **시험 코드를 하나도 못 찾았으면 «신선하다» 가 아니다** — 결함 310.
    #   `newest` 가 0 이면 비교가 늘 거짓이라 **조용히 통과**한다.
    #   결함 99 가 이름 붙인 그것이다: **침묵과 통과는 다르다.**
    if not seen:
        return {"합": n, "낡음": True, "범인": "시험 코드를 하나도 못 찾았다",
                "언제": d.get("언제"), "어디서": d.get("어디서")}
    # ⚠ **`.new` 가 옆에 있으면 이 파일은 갱신에 실패한 판이다** — 결함 310.
    #   `safeio` 는 백업이 막히면 원본을 안 덮고 `.new` 에 쓴다. 그때
    #   원본은 **옛 수를 든 채 mtime 도 안 바뀌므로** 낡음 검사에도 안 걸린다.
    if os.path.exists(p + ".new"):
        return {"합": n, "낡음": True,
                "범인": "%s.new 가 있다 — 마지막 갱신이 원본에 못 들어갔다"
                        % TRUTH_FILE,
                "언제": d.get("언제"), "어디서": d.get("어디서")}
    stale = newest > os.path.getmtime(p)
    return {"합": n, "낡음": stale, "범인": who if stale else None,
            "언제": d.get("언제"), "어디서": d.get("어디서")}


def write_truth(root: str, phase1: int, phase2: int) -> dict:
    """`preflight` 이 시험을 **실제로 돌린 직후** 부른다.

    ⚠ `phase1`·`phase2` 는 **전체 수**(통과+실패)다 — 09-18 에
    «통과 수» 에서 바꿨다. 통과만 세면 **시험 하나가 실패할 때마다
    정본이 1 내려가** 문서와 어긋나고, 고치면 또 올라간다.
    09-16~18 에 그 «한 칸씩 쫓아다니기» 를 세 번 돌았다.
    이유 전문은 `preflight.py` 의 `n = int(hits[-1][0]) + …` 주석.

    ⚠ **결과 딕셔너리를 돌려준다** (결함 310). 앞판은 경로만 돌려줬는데,
    `safeio` 가 **백업이 막히면 원본을 안 덮고 `.new` 에 쓴다.** 그때
    화면은 조용하고 정본 파일은 **옛 수를 든 채** 남는다 — 그리고
    `mtime` 이 안 바뀌므로 낡음 검사에도 안 걸린다. **거짓 초록이다.**
    부르는 쪽이 `원본유지` 를 보고 소리를 내야 한다.
    """
    import datetime as _dt2
    import platform as _pf
    # ⚠ **맨 `json.dump` 를 쓰지 않는다** — 시험 [129]가 `bench/` 의 맨
    #   `json.dump` 수를 24로 잠가 뒀고, 내가 여기서 25로 만들어 즉시
    #   빨개졌다. **문턱을 올리는 것이 아니라 공용 함수를 쓰는 것이 답이다**
    #   (그 시험이 «줄이는 쪽으로 바꿀 때만 상수를 내려라» 라고 적어 뒀다).
    #   덤 — 앞 판이 `.bak` 으로 남아 **정본이 언제 몇이었는지**가 보존된다.
    from ..io import safeio as _safe
    p = os.path.join(root, TRUTH_FILE)
    return _safe.save_json(
        {"phase1": phase1, "phase2": phase2, "합": phase1 + phase2,
         "언제": _dt2.datetime.now().isoformat(timespec="seconds"),
         "어디서": _pf.node()}, p)


