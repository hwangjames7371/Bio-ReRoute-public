#   맞았다. `넉 달`·`다섯 달` 이 **문서 27개에 99번** 있었고 이 저장소
#   안에 근거가 **하나도 없다.** 가장 오래된 파일이 08-03, 첫 커밋이
#   08-05 다. 실제는 **약 6주**이고 우리는 그 2.7~3.4배를 적고 있었다.
#
#   **자기 비판이라 아무도 안 뒤졌다.** *"넉 달 동안 모의로만 돌렸다"* 는
#   우리를 나쁘게 만드는 문장이라 검증 본능이 안 걸렸다. 유리한 숫자는
#   의심받고 **불리한 숫자는 그냥 통과한다** — 그게 이 결함의 교훈이다.
#
#   가장 이른 착수일을 쓴다. **가장 관대한 경계**라서, 여기 걸리면
#   어떻게 읽어도 틀린 것이다.
PROJECT_START = _dt.date(2026, 7, 1)

_NUM = {"한": 1, "두": 2, "세": 3, "네": 4, "넉": 4, "다섯": 5, "여섯": 6,
        "일곱": 7, "여덟": 8, "아홉": 9, "열": 10}
# `동안·째·만에` 만 본다. **`N 달 전` 은 안 본다** — 그건 외부 사건을
# 가리킬 수 있고, 실제로 결함 95(특허 API 가 다섯 달 전 중단)가 그렇다.
_SPAN = re.compile(r"(한|두|세|네|넉|다섯|여섯|일곱|여덟|아홉|열)\s*달\s*(동안|째|만에)"
                   r"|(\d+)\s*개월\s*(동안|째|만에)")


def duration_errors(root: str = ROOT, today: Optional[_dt.date] = None
                    ) -> List[Dict[str, Any]]:
    """문서가 주장하는 **작업 기간**이 실제 경과보다 길면 잡는다."""
    d = today or _dt.date.today()
    elapsed = (d - PROJECT_START).days / 30.44
    out = []
    for fn in sorted(set(DOCS)) + ["slides/build_deck.py", "CLAUDE.md"]:
        p = os.path.join(root, fn)
        if not os.path.exists(p):
            continue
        try:
            txt = open(p, encoding="utf-8").read()
        except Exception:
            continue
        skip = _fenced(txt) if fn.endswith(".md") else set()
        for m in _SPAN.finditer(txt):
            ln = txt[:m.start()].count("\n") + 1
            if ln in skip:
                continue
            n = _NUM.get(m.group(1)) if m.group(1) else int(m.group(3))
            if n > elapsed:
                out.append({"파일": fn, "줄": ln, "적힌 것": m.group(0).strip(),
                            "실제 경과": round(elapsed, 1)})
    return out


def _pptx_text(path: str) -> str:
    """pptx 슬라이드의 글자만 뽑는다.

    ## 이 함수가 왜 생겼나 — 가드의 사각지대 (결함 60)

    이 검사기를 만들 때 `.md` 만 읽게 했다. 그런데 **본선 제출물 넷 중
    둘이 md 가 아니다** — 발표자료(pptx)와 보고서(pdf).

    실측: 08-06 밤에 pptx 를 열어 보니 **08-05 상태에 멈춰 있었다.**

    ```
    슬라이드가 말하는 것    결함 39건 · 38건(같은 파일 안에서 불일치) · 시험 466건
    실제                   결함 59건 · 시험 649건
    ECE · 정답표 감사 · 선행연구 · 의료 면책   →  **한 장도 없음**
    ```

    4~7차 검토에서 나온 것이 **하나도 반영되지 않았다.** 그리고 문서
    일관성 가드는 그걸 못 봤다 — **가드가 안 보는 곳이 가장 오래 낡는다.**

    pdf 는 md 에서 생성하므로 md 만 맞으면 따라온다. pptx 는
    `slides/build_deck.py` 라는 **별도 소스**가 있어 따로 어긋난다.
    """
    try:
        import zipfile
        z = zipfile.ZipFile(path)
    except Exception:
        return ""
    out = []
    for n in sorted(z.namelist()):
        if n.startswith("ppt/slides/slide") and n.endswith(".xml"):
            try:
                out.append(re.sub(r"<[^>]+>", " ", z.read(n).decode("utf-8")))
            except Exception:
                continue
    return "\n".join(out)


