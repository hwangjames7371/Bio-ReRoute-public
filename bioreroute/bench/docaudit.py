#   결과를 보기 전에 적고 잠근 예측이다. `사전명세_보정.md:14` 의
#   «기준선이 더 정직하다» 는 낡은 주장이 아니라 **틀린 것으로 판명된
#   사전 예측**이고, 그게 남아 있는 것이 이 방법의 요점이다.
#
#   목록을 손으로 적지 않는다 — `*_봉인.json` 이 가리키는 것을 쓴다.
#   **손목록은 곧 낡는다**(결함 60 계열). 봉인 없는 `사전명세*.md` 는
#   여기 안 잡히고 `preflight` 렌즈 8에서 ⚠ 로 뜬다. 그게 맞다.
def _item(r, prefix):
    """감사 결과에서 그 이름으로 시작하는 항목 하나."""
    for it in r.get("항목") or []:
        if str(it.get("이름") or "").startswith(prefix):
            return it
    return None


