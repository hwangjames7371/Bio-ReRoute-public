def _md_steps(steps, done=False):
    """돌고 있는 동안 보여줄 것. **단계를 글자로 남긴다.**

    제안서 §6이 요구한 것이 이것이다 —

      > 각 후보가 깔때기를 통과하거나 탈락하는 단계(F0 → 라우터 → S1–S3
      > → 규제)를 **실시간 진행 표시**로 보여주고

    회전하는 아이콘만으로는 *"돌고 있다"* 밖에 못 말한다. **어느 게이트에서
    무엇을 보고 있는지**를 적어야 §6 이다.
    """
    # ── **같은 게이트를 두 줄로 쌓지 않는다** ────────────────────────
    #   `run_pair` 는 게이트마다 두 번 부른다 — `실행 중` 과 결과.
    #   그대로 쌓으면 08-11 실측처럼 *"9단계"* 가 뜨는데 실제 게이트는
    #   다섯이다. **화면이 단계 수를 부풀린다.** 뒤에 온 것으로 덮는다.
    seen, order = {}, []
    for stage, detail in steps:
        if stage not in seen:
            order.append(stage)
        seen[stage] = detail
    head = ("### 마무리 중…" if done
            else "### 검증 중… (게이트 %d개)" % len(order))
    L = [head, ""]
    for i, stage in enumerate(order, 1):
        d = seen[stage]
        mark = "**…**" if (d or "").strip() in ("실행 중", "") else "**%s**" % d
        L.append("%d. %s — %s" % (i, stage, mark))
    if not done:
        L.append("")
        L.append("*멈춘 게 아니다. PubMed·LLM 응답을 기다리는 중이다.*")
    return "\n".join(L)


