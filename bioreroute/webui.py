def _plddt_cell(pl):
    """pLDDT 칸. **없으면 «모름» 이지 `None` 이 아니다.**

    앞판은 `pl.get("mean")` 을 그대로 찍었다. 키가 없으면 화면에
    **문자 그대로 `None`** 이 나온다 — 결함 89 가 잡은 그 형태다.
    (`rifampin` 은 91.1 이 있어서 안 드러났다. **드러나는 사례로만
    확인하면 검증이 아니다** — CLAUDE.md §5)
    """
    v = pl.get("mean") if isinstance(pl, dict) else pl
    if v is None:
        return "모름"
    try:
        return "%.1f" % float(v)
    except (TypeError, ValueError):
        return str(v)


